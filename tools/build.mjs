#!/usr/bin/env node
// Builds every page of the site from src/ and assets/catalog.json:
//
//   index.html               home page                      (src/pages/home.html)
//   catalogo/index.html      catalog with search and filters (src/pages/catalog.html)
//   catalogo/<category>.html plain list of a category, for search engines and for visitors without JavaScript
//   p/<id>.html              one page per product
//   404.html                 shown for addresses that do not exist
//   sitemap.xml
//
//   node tools/build.mjs
//
// The pages are committed to the repository because the site is served as static files. Do not edit them by
// hand: change src/, data/ or this script and build again. Everything inside p/ and catalogo/ is rewritten.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cardHtml, esc, fmt, fromRow, icon, pageUrl, waProduct } from '../assets/js/card.js';

const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SITE = 'https://carbelec.co';
const FEATURED_ON_HOME = 8;
const RELATED = 4;
// Products shown beside the title of the home page: rotary hammer, angle grinder, cordless drill, socket set.
const HERO_SHOTS = ['MCO3503282342', 'MCO1826876923', 'MCO854831192', 'MCO1587817033'];
// key: category in the data; label: Spanish name; i18n: key of its translated name in assets/js/core.js
const CATEGORIES = [
  { key: 'herramientas', label: 'Herramientas', i18n: 'cat_tools' },
  { key: 'repuestos', label: 'Repuestos', i18n: 'cat_parts' },
  { key: 'electricos', label: 'Eléctricos', i18n: 'cat_elec' },
  { key: 'hogar', label: 'Hogar', i18n: 'cat_home' },
  { key: 'construccion', label: 'Construcción', i18n: 'cat_build' },
  { key: 'seguridad', label: 'Seguridad Industrial', i18n: 'cat_safety' }
];
const categoryOf = key => CATEGORIES.find(c => c.key === key);

const read = file => fs.readFileSync(path.join(REPO, file), 'utf8');
const pesos = new Intl.NumberFormat('es-CO');
const jsonLd = data => JSON.stringify(data).replace(/</g, '\\u003c');
const indent = (text, spaces) => text.split('\n').map(line => (line ? ' '.repeat(spaces) + line : line)).join('\n');

// ── Products ────────────────────────────────────────────────────────────────
const products = JSON.parse(read('assets/catalog.json')).map(fromRow);
for (const p of products) {
  if (!/^MCO\d+$/.test(p.id)) throw new Error('Bad product id: ' + p.id);
  if (!categoryOf(p.cat)) throw new Error('Unknown category "' + p.cat + '" in ' + p.id);
  if (!/^https:\/\/(www|articulo)\.mercadolibre\.com\.co\//.test(p.url)) throw new Error('Bad link in ' + p.id);
  if (!fs.existsSync(path.join(REPO, p.img))) throw new Error('Missing photo ' + p.img + ' of ' + p.id);
}
if (new Set(products.map(p => p.id)).size !== products.length) throw new Error('Duplicate product ids');
const groups = Object.fromEntries(CATEGORIES.map(c => [c.key, products.filter(p => p.cat === c.key)]));
const featured = JSON.parse(read('data/featured.json')).map(item => products.find(p => p.id === item.id));

// ── Page shell ──────────────────────────────────────────────────────────────
// Limits what a page may load or contact, so injected content cannot pull in outside scripts or send data
// elsewhere. When adding an outside service (fonts, form, chatbot), add its address here too.
const CSP = "default-src 'self'; script-src 'self'; style-src 'self' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; " +
  "img-src 'self' data:; connect-src 'self' https://formsubmit.co https://carbelec-chatbot.dei0821.workers.dev; " +
  "object-src 'none'; base-uri 'self'; form-action 'self'";
const NAV = read('src/partials/nav.html').trimEnd();
const FOOTER = read('src/partials/footer.html').trimEnd();

function shell({ title, description, canonical, image = SITE + '/assets/logo.png', titleKey = '', mainClass = '', body, scripts = [], structured = [] }) {
  return `<!DOCTYPE html>
<!-- Generated by tools/build.mjs from src/ — do not edit this file by hand. -->
<html lang="es"${titleKey ? ` data-title-key="${titleKey}"` : ''}>
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta http-equiv="Content-Security-Policy" content="${CSP}">
  <meta name="referrer" content="strict-origin-when-cross-origin">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <link rel="canonical" href="${esc(canonical)}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="CARBELEC">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${esc(canonical)}">
  <meta property="og:image" content="${esc(image)}">
  <meta property="og:locale" content="es_CO">
${structured.map(data => `  <script type="application/ld+json">${jsonLd(data)}</script>`).join('\n')}
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=DM+Sans:ital,opsz,wght@0,9..40,300;0,9..40,400;0,9..40,500;0,9..40,600;0,9..40,700;1,9..40,400&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/assets/site.css">
${['main', ...scripts].map(name => `  <script type="module" src="/assets/js/${name}.js"></script>`).join('\n')}
</head>
<body>
${indent(NAV, 2)}

  <main${mainClass ? ` class="${mainClass}"` : ''}>
${indent(body.trimEnd(), 2)}
  </main>

${indent(FOOTER, 2)}
</body>
</html>
`;
}

const crumbs = items => ({
  '@context': 'https://schema.org', '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, url], index) => ({ '@type': 'ListItem', position: index + 1, name, item: url }))
});

// ── Home ────────────────────────────────────────────────────────────────────
function homePage() {
  const description = 'Ferretería CARBELEC en Bogotá. Más de 1.600 productos de ferretería, eléctricos, repuestos y herramientas. Envío gratis a todo Colombia.';
  const cards = featured.slice(0, FEATURED_ON_HOME).map(p => indent(cardHtml(p), 6)).join('\n');
  const shots = HERO_SHOTS.map(id => products.find(p => p.id === id)).map(p =>
    `      <a class="shot" href="${pageUrl(p.id)}"><span class="shot-img"><img src="${esc(p.img)}" alt="" width="640" height="640"></span>`
    + `<span class="shot-name" data-pname="${p.id}">${esc(p.name)}</span><span class="shot-price">${fmt(p.price)}</span></a>`).join('\n');
  const store = {
    '@context': 'https://schema.org', '@type': 'HardwareStore', name: 'CARBELEC — Carbon Electric S.A.S.',
    url: SITE + '/', image: SITE + '/assets/logo.png', telephone: '+57 315 389 9483',
    address: { '@type': 'PostalAddress', streetAddress: 'Cra. 81 #73F Sur 57', addressLocality: 'Bogotá', addressRegion: 'Cundinamarca', addressCountry: 'CO' },
    openingHoursSpecification: [
      { '@type': 'OpeningHoursSpecification', dayOfWeek: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday'], opens: '08:30', closes: '19:00' },
      { '@type': 'OpeningHoursSpecification', dayOfWeek: 'Saturday', opens: '09:30', closes: '18:00' }
    ],
    sameAs: ['https://www.mercadolibre.com.co/pagina/ferreteriacarbelec', 'https://www.facebook.com/p/Ferreter%C3%ADa-Carbelec-100056033332482/']
  };
  return shell({
    title: 'CARBELEC S.A.S. | Carbon Electric — Ferretería en Bogotá', description, canonical: SITE + '/', titleKey: 'meta',
    body: read('src/pages/home.html').replace('{{featured}}', cards).replace('{{heroShots}}', shots), scripts: ['home'], structured: [store]
  });
}

// ── Catalog ─────────────────────────────────────────────────────────────────
function catalogPage() {
  const links = CATEGORIES.map(c => `<a href="/catalogo/${c.key}.html" data-i18n="${c.i18n}">${esc(c.label)}</a>`).join(' · ');
  return shell({
    title: 'Catálogo | CARBELEC', canonical: SITE + '/catalogo/', titleKey: 'cat_meta', mainClass: 'page',
    description: `Catálogo de la ferretería CARBELEC en Bogotá: ${pesos.format(products.length)} productos de ferretería, repuestos, eléctricos y seguridad con precio de referencia.`,
    body: read('src/pages/catalog.html').replace('{{categoryLinks}}', links), scripts: ['catalog'],
    structured: [crumbs([['Inicio', SITE + '/'], ['Catálogo', SITE + '/catalogo/']])]
  });
}

function categoryPage(category) {
  const list = groups[category.key];
  const canonical = `${SITE}/catalogo/${category.key}.html`;
  const body = `<section class="sec">
  <p class="crumbs"><a href="/" data-i18n="nav_home">Inicio</a> › <a href="/catalogo/" data-i18n="prod_label">Catálogo</a></p>
  <h1 class="sec-title" data-i18n="${category.i18n}">${esc(category.label)}</h1>
  <p class="sec-desc">${pesos.format(list.length)} productos. <a href="/catalogo/?cat=${category.key}">Verlos con fotos, buscador y filtros</a>.</p>
  <ul class="plist">
${list.map(p => `    <li><a href="${pageUrl(p.id)}" data-pname="${p.id}">${esc(p.name)}</a> <span>${fmt(p.price)}</span></li>`).join('\n')}
  </ul>
</section>`;
  return shell({
    title: `${category.label} | Catálogo CARBELEC`, canonical, mainClass: 'page', body,
    description: `${pesos.format(list.length)} productos de ${category.label.toLowerCase()} en la ferretería CARBELEC, Bogotá. Precios de referencia y envío a todo Colombia por MercadoLibre.`,
    structured: [crumbs([['Inicio', SITE + '/'], ['Catálogo', SITE + '/catalogo/'], [category.label, canonical]])]
  });
}

// ── Product ─────────────────────────────────────────────────────────────────
// A few products of the same category, the ones that follow it in the catalog.
function relatedTo(p) {
  const list = groups[p.cat];
  const at = list.indexOf(p);
  return Array.from({ length: Math.min(RELATED, list.length - 1) }, (_, i) => list[(at + 1 + i) % list.length]);
}

function productPage(p) {
  const category = categoryOf(p.cat);
  const canonical = SITE + pageUrl(p.id);
  const image = SITE + p.img;
  const description = `${p.name}. Precio de referencia ${fmt(p.price)} COP. Ferretería CARBELEC en Bogotá: compra en MercadoLibre con envío a todo Colombia o cotiza por WhatsApp.`;
  const body = `<section class="sec">
  <p class="crumbs"><a href="/" data-i18n="nav_home">Inicio</a> › <a href="/catalogo/" data-i18n="prod_label">Catálogo</a> › <a href="/catalogo/?cat=${p.cat}" data-i18n="${category.i18n}">${esc(category.label)}</a></p>
  <article class="product" data-id="${p.id}" data-name="${esc(p.name)}" data-price="${p.price}">
    <div class="pd-photo"><img src="${esc(p.img)}" alt="${esc(p.name)}" width="640" height="640"></div>
    <div>
      ${p.brand ? `<p class="pd-brand">${esc(p.brand)}</p>` : ''}
      <h1 class="pd-name" data-pname="${p.id}">${esc(p.name)}</h1>
      ${p.desc ? `<p class="pd-desc" data-pdesc="${p.id}">${esc(p.desc)}</p>` : ''}
      <p class="pd-price">${fmt(p.price)} <span>COP</span></p>
      <p class="pd-note" data-i18n="pd_note">Precio de referencia. El precio final y la disponibilidad son los publicados en MercadoLibre.</p>
      <p class="pd-actions">
        <a class="btn btn-gold" href="${esc(p.url)}" target="_blank" rel="noopener">${icon('bag')} <span data-i18n="hero_btn_ml">Comprar en MercadoLibre</span></a>
        <button type="button" class="btn btn-out pd-add js-add" aria-pressed="false">${icon('plus')} <span data-add-label>Agregar a mi cotización</span></button>
        <a class="btn btn-wa" href="${esc(waProduct(p))}" target="_blank" rel="noopener">${icon('whatsapp')} <span data-i18n="pd_wa">Cotizar por WhatsApp</span></a>
      </p>
      <p class="pd-more"><a href="/catalogo/?cat=${p.cat}" data-i18n="pd_more">Ver más productos de esta categoría</a></p>
    </div>
  </article>
  <h2 class="rel-title" data-i18n="rel_title">Productos relacionados</h2>
  <div class="pgrid">
${relatedTo(p).map(other => indent(cardHtml(other), 4)).join('\n')}
  </div>
</section>`;
  const product = {
    '@context': 'https://schema.org', '@type': 'Product', name: p.name, image, sku: p.id, category: category.label,
    offers: { '@type': 'Offer', price: p.price, priceCurrency: 'COP', url: p.url, seller: { '@type': 'Organization', name: 'CARBELEC — Carbon Electric S.A.S.' } }
  };
  if (p.brand) product.brand = { '@type': 'Brand', name: p.brand };
  if (p.desc) product.description = p.desc;
  return shell({
    title: `${p.name} | CARBELEC`, description, canonical, image, mainClass: 'page', body,
    structured: [product, crumbs([['Inicio', SITE + '/'], ['Catálogo', SITE + '/catalogo/'], [category.label, `${SITE}/catalogo/?cat=${p.cat}`], [p.name, canonical]])]
  });
}

// ── Not found ───────────────────────────────────────────────────────────────
// GitHub Pages serves 404.html for any address that does not exist.
function notFoundPage() {
  const body = `<section class="sec">
  <p class="sec-lbl">404</p>
  <h1 class="sec-title" data-i18n="nf_title">No encontramos esa página.</h1>
  <p class="sec-desc" data-i18n="nf_text">Puede que el producto ya no esté disponible o que la dirección haya cambiado.</p>
  <p class="pd-actions">
    <a class="btn btn-gold" href="/catalogo/">${icon('search')} <span data-i18n="feat_cta">Ver el catálogo completo</span></a>
    <a class="btn btn-out" href="/"><span data-i18n="nav_home">Inicio</span></a>
  </p>
</section>`;
  return shell({ title: 'Página no encontrada | CARBELEC', description: 'La página que buscas no existe en carbelec.co.', canonical: SITE + '/', mainClass: 'page', body });
}

// ── Write ───────────────────────────────────────────────────────────────────
function freshDir(name) {
  const dir = path.join(REPO, name);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

fs.writeFileSync(path.join(REPO, 'index.html'), homePage());
fs.writeFileSync(path.join(REPO, '404.html'), notFoundPage());

const catalogDir = freshDir('catalogo');
fs.writeFileSync(path.join(catalogDir, 'index.html'), catalogPage());
for (const category of CATEGORIES) fs.writeFileSync(path.join(catalogDir, category.key + '.html'), categoryPage(category));

const productDir = freshDir('p');
for (const p of products) fs.writeFileSync(path.join(productDir, p.id + '.html'), productPage(p));

const urls = [SITE + '/', SITE + '/catalogo/', ...CATEGORIES.map(c => `${SITE}/catalogo/${c.key}.html`),
  ...products.map(p => SITE + pageUrl(p.id)), SITE + '/privacidad/'];
fs.writeFileSync(path.join(REPO, 'sitemap.xml'),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map(url => `  <url><loc>${esc(url)}</loc></url>`).join('\n') + '\n</urlset>\n');

console.log(`home, catalog, ${CATEGORIES.length} category pages, ${products.length} product pages, ${urls.length} sitemap entries`);
